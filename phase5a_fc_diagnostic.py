"""
phase5a_fc_diagnostic.py -- Phase 5A: diagnostic Pearson FC construction and
audit, preserving undefined correlations explicitly as NaN. NO Fisher-Z on
real data, NO SVM-RFE/SSAE/classifier training, NO full FC dataset written
to disk (per-subject matrices are computed in-memory and immediately
reduced to aggregate audit statistics, never persisted).

Read-only against Phase 1-4.2 outputs and the source .1D files.
"""
from __future__ import annotations

import json
import warnings
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(r"C:\abide")
PHASE2_FILTERED = ROOT / "results" / "phase2" / "fd_filtered_subjects.csv"
AAL_DIR = ROOT / "abide_pcp" / "ABIDE_pcp" / "cpac" / "filt_global"
PHASE4_1_DIR = ROOT / "results" / "phase4_1_constant_roi_audit"

OUT_DIR = ROOT / "results" / "phase5a_fc_diagnostic"
OUT_DIR.mkdir(parents=True, exist_ok=True)

GUARD_DIRS = [
    ROOT / "results" / "phase1", ROOT / "results" / "phase2", ROOT / "results" / "phase3",
    ROOT / "results" / "phase3_5", ROOT / "results" / "phase3_6",
    ROOT / "results" / "phase3_6_verification", ROOT / "results" / "phase3_6_aal_download",
    ROOT / "results" / "phase4", ROOT / "results" / "phase4_1_constant_roi_audit",
    ROOT / "results" / "phase4_2_methodological_sensitivity",
]

audit_lines = []
EXPECTED_UNDEFINED_TOTAL = 14025


def log(msg: str):
    line = f"[{datetime.now(timezone.utc).isoformat()}] {msg}"
    audit_lines.append(line)
    print(msg, flush=True)


def fp_snapshot(root: Path) -> dict:
    out = {}
    if root.exists():
        for p in root.rglob("*"):
            if p.is_file():
                st = p.stat()
                out[str(p)] = (st.st_size, st.st_mtime)
    return out


def guard_fingerprints() -> dict:
    fps = {}
    for d in GUARD_DIRS:
        fps.update(fp_snapshot(d))
    return fps


def normalize_id(raw) -> str:
    s = str(raw).strip()
    try:
        return str(int(float(s)))
    except (ValueError, TypeError):
        return s


def extract_subject_id(name: str) -> str | None:
    base = name.replace("_rois_aal.1D", "")
    digits = "".join(ch for ch in base.split("_")[-1] if ch.isdigit())
    return str(int(digits)) if digits else None


def main():
    log("=" * 60)
    log("PHASE 5A -- Diagnostic Pearson FC construction (NaN preserved, no Fisher-Z/SVM-RFE/training).")
    log("=" * 60)
    pre_guard = guard_fingerprints()
    status_ok = True  # flips to False on any prohibited-operation or cross-check failure

    # ── authoritative inputs (read-only) ────────────────────────────────
    cohort = pd.read_csv(PHASE2_FILTERED, dtype={"subject_id": str})
    cohort["subject_id_norm"] = cohort["subject_id"].map(normalize_id)
    n_cohort, n_asd, n_control = len(cohort), int((cohort.diagnosis == "ASD").sum()), int((cohort.diagnosis == "Control").sum())
    assert n_cohort == 780 and n_asd == 351 and n_control == 429
    cohort_lookup = cohort.set_index("subject_id_norm")
    log(f"Cohort: {n_cohort} ({n_asd} ASD, {n_control} Control), 20 sites -- verified unchanged.")

    roi_mapping = pd.read_csv(PHASE4_1_DIR / "aal116_roi_mapping.csv")
    roi_name = roi_mapping.set_index("roi_index")["roi_name"].to_dict()

    id_to_file = {}
    for f in AAL_DIR.glob("*_rois_aal.1D"):
        sid = extract_subject_id(f.name)
        if sid:
            id_to_file[sid] = f
    subject_files = {sid: id_to_file[sid] for sid in cohort["subject_id_norm"] if sid in id_to_file}
    assert len(subject_files) == 780

    # ── feature indexing convention (deterministic, documented) ─────────
    # feature_index = 1..6670, 0-indexed ROI pair (i, j) with i < j, generated by
    # a row-major nested loop: outer i = 0..114, inner j = i+1..115.
    # roi_i / roi_j reported as 1-indexed ROI numbers (matching Phase 4.1 convention).
    # This is symmetric to "lower triangle" by definition (corr[i,j] == corr[j,i]);
    # the (i<j) ordering is the one, single convention used everywhere below.
    feature_rows = []
    idx = 1
    pair_to_feature = {}
    for i in range(116):
        for j in range(i + 1, 116):
            feature_rows.append({
                "feature_index": idx, "roi_i": i + 1, "roi_j": j + 1,
                "roi_i_name": roi_name.get(i + 1), "roi_j_name": roi_name.get(j + 1),
            })
            pair_to_feature[(i, j)] = idx
            idx += 1
    feature_index_df = pd.DataFrame(feature_rows)
    assert len(feature_index_df) == 6670
    feature_index_df.to_csv(OUT_DIR / "fc_feature_index.csv", index=False)
    log(f"fc_feature_index.csv written: {len(feature_index_df)} features. Convention: 0-indexed ROI "
        f"pairs (i,j), i<j, outer loop i=0..114 row-major, inner loop j=i+1..115; feature_index=1..6670; "
        f"roi_i/roi_j reported 1-indexed. Deterministic and fixed for the remainder of this project.")

    # ── PHASE 5A core: per-subject Pearson FC (in-memory only, never persisted) ──
    log("\nComputing 116x116 Pearson FC per subject (in-memory; only aggregate audit stats are saved)...")
    total_undefined = 0
    undefined_per_feature = np.zeros(6670, dtype=int)
    subject_summary_rows = []
    validation_issues = []
    exact_plus1 = 0
    exact_minus1 = 0
    manual_check_rows = []
    diag_nonconstant_not_one = 0
    diag_constant_not_nan = 0
    asymmetry_count = 0
    out_of_range_count = 0
    undefined_where_both_nonconstant = 0
    defined_where_either_constant = 0

    subj_order = list(cohort["subject_id_norm"])
    rng = np.random.default_rng(42)
    manual_check_targets = set()  # (subject_index, pair) sampled for independent formula check

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")  # expected RuntimeWarning from zero-std divisions
        for s_idx, sid in enumerate(subj_order):
            row = cohort_lookup.loc[sid]
            arr = np.loadtxt(str(subject_files[sid]))
            if arr.ndim == 1:
                arr = arr.reshape(-1, 1)
            assert arr.shape[1] == 116, f"Subject {sid}: expected 116 columns, got {arr.shape[1]}"

            stds = np.std(arr, axis=0)
            const_mask = (stds == 0.0)
            corr = np.corrcoef(arr, rowvar=False)  # 116x116, NaN where std==0 (numpy's own behavior)

            # -- numerical validation --
            for k in range(116):
                if const_mask[k]:
                    if not np.isnan(corr[k, k]):
                        diag_constant_not_nan += 1
                else:
                    if not np.isclose(corr[k, k], 1.0, atol=1e-8, equal_nan=False):
                        diag_nonconstant_not_one += 1

            iu = np.triu_indices(116, k=1)
            il = (iu[1], iu[0])
            upper_vals = corr[iu]
            lower_vals = corr[il]
            both_finite = ~np.isnan(upper_vals) & ~np.isnan(lower_vals)
            if not np.allclose(upper_vals[both_finite], lower_vals[both_finite], atol=1e-10):
                asymmetry_count += 1
            defined_vals = upper_vals[~np.isnan(upper_vals)]
            if len(defined_vals) and ((defined_vals < -1.0 - 1e-8).any() or (defined_vals > 1.0 + 1e-8).any()):
                out_of_range_count += 1

            n_undefined_this_subject = 0
            for k, (i, j) in enumerate(zip(*iu)):
                val = corr[i, j]
                pair_const = const_mask[i] or const_mask[j]
                is_nan = np.isnan(val)
                if is_nan and not pair_const:
                    undefined_where_both_nonconstant += 1
                if (not is_nan) and pair_const:
                    defined_where_either_constant += 1
                if is_nan:
                    n_undefined_this_subject += 1
                    undefined_per_feature[k] += 1
                else:
                    if val >= 1.0 - 1e-9:
                        exact_plus1 += 1
                    if val <= -1.0 + 1e-9:
                        exact_minus1 += 1

            total_undefined += n_undefined_this_subject
            subject_summary_rows.append({
                "subject_id": sid, "diagnosis": row["diagnosis"], "site": row.get("site"),
                "constant_roi_count": int(const_mask.sum()),
                "undefined_fc_count": n_undefined_this_subject,
                "undefined_fc_percentage": round(100 * n_undefined_this_subject / 6670, 4),
            })

            # independent manual-formula spot check: sample up to 2 pairs per subject
            n_sample = min(2, 116)
            sample_is = rng.choice(116, size=n_sample, replace=False)
            for i in sample_is:
                j = int(rng.integers(0, 116))
                if j == i:
                    continue
                lo, hi = min(i, j), max(i, j)
                xi, xj = arr[:, lo], arr[:, hi]
                if np.std(xi) == 0 or np.std(xj) == 0:
                    manual_r = np.nan
                else:
                    manual_r = float(np.corrcoef(xi, xj)[0, 1])
                    # also cross-check via raw formula, not numpy's corrcoef, for true independence
                    cov = np.mean((xi - xi.mean()) * (xj - xj.mean()))
                    manual_r_formula = cov / (np.std(xi) * np.std(xj))
                    manual_check_rows.append({
                        "subject_id": sid, "roi_i": lo + 1, "roi_j": hi + 1,
                        "corrcoef_value": float(corr[lo, hi]),
                        "manual_formula_value": float(manual_r_formula),
                        "match": bool(np.isclose(corr[lo, hi], manual_r_formula, atol=1e-8)),
                    })

    log(f"Per-subject FC computed for all {len(subj_order)} subjects.")

    # ── cross-check #1: total undefined == 14,025 ────────────────────────
    cross_check_pass = (total_undefined == EXPECTED_UNDEFINED_TOTAL)
    log(f"CROSS-CHECK: sum(undefined FC entries) = {total_undefined}  (expected {EXPECTED_UNDEFINED_TOTAL})  "
        f"-> {'PASS' if cross_check_pass else 'FAIL -- STOP CONDITION'}")
    if not cross_check_pass:
        status_ok = False
        log("[STOP] Cross-check failed. Investigate discrepancy before proceeding further.")

    # ── validation summary ────────────────────────────────────────────────
    validation_pass = (diag_nonconstant_not_one == 0 and diag_constant_not_nan == 0 and
                       asymmetry_count == 0 and out_of_range_count == 0 and
                       undefined_where_both_nonconstant == 0 and defined_where_either_constant == 0)
    log(f"VALIDATION: diag!=1(nonconstant ROIs)={diag_nonconstant_not_one}, "
        f"diag!=NaN(constant ROIs)={diag_constant_not_nan}, asymmetric subjects={asymmetry_count}, "
        f"out-of-range subjects={out_of_range_count}, undefined-but-both-nonconstant={undefined_where_both_nonconstant}, "
        f"defined-but-either-constant={defined_where_either_constant} -> "
        f"{'PASS' if validation_pass else 'FAIL'}")
    manual_df = pd.DataFrame(manual_check_rows)
    manual_match = bool(manual_df["match"].all()) if len(manual_df) else None
    log(f"INDEPENDENT FORMULA CHECK: {len(manual_df)} sampled (subject, ROI-pair) entries computed via "
        f"raw covariance/std formula (not np.corrcoef) -- all_match={manual_match}")
    validation_pass = validation_pass and bool(manual_match)
    if not validation_pass:
        status_ok = False

    # ── undefined_fc_features.csv ────────────────────────────────────────
    undefined_features_df = feature_index_df.copy()
    undefined_features_df["number_subjects_undefined"] = undefined_per_feature
    undefined_features_df["percentage_subjects_undefined"] = np.round(
        100 * undefined_per_feature / n_cohort, 4)
    undefined_features_df.to_csv(OUT_DIR / "undefined_fc_features.csv", index=False)
    log(f"undefined_fc_features.csv written ({len(undefined_features_df)} rows).")

    subject_summary_df = pd.DataFrame(subject_summary_rows)
    subject_summary_df.to_csv(OUT_DIR / "undefined_fc_subject_summary.csv", index=False)
    log(f"undefined_fc_subject_summary.csv written ({len(subject_summary_df)} rows).")

    site_rows = []
    for site, g in subject_summary_df.groupby("site"):
        affected = g[g["undefined_fc_count"] > 0]
        site_rows.append({
            "site": site, "total_subjects": len(g), "affected_subjects": len(affected),
            "total_undefined_entries": int(g["undefined_fc_count"].sum()),
            "mean_undefined_per_subject": float(g["undefined_fc_count"].mean()),
            "median_undefined_per_subject": float(g["undefined_fc_count"].median()),
            "max_undefined_per_subject": int(g["undefined_fc_count"].max()),
        })
    site_summary_df = pd.DataFrame(site_rows).sort_values("total_undefined_entries", ascending=False)
    site_summary_df.to_csv(OUT_DIR / "undefined_fc_site_summary.csv", index=False)
    log(f"undefined_fc_site_summary.csv written ({len(site_summary_df)} sites).")

    # ── missingness structure / thresholds ───────────────────────────────
    pct = undefined_features_df["percentage_subjects_undefined"].values
    thresholds = {"n_features_affected_any": int((pct > 0).sum()),
                  "n_features_ge_1pct": int((pct >= 1).sum()),
                  "n_features_ge_5pct": int((pct >= 5).sum()),
                  "n_features_ge_10pct": int((pct >= 10).sum()),
                  "n_features_ge_25pct": int((pct >= 25).sum()),
                  "n_features_ge_50pct": int((pct >= 50).sum()),
                  "max_subjects_affected_single_feature": int(undefined_per_feature.max()),
                  "total_features": 6670}
    thresholds_df = pd.DataFrame([thresholds])
    thresholds_df.to_csv(OUT_DIR / "fc_missingness_thresholds.csv", index=False)
    log(f"fc_missingness_thresholds.csv written: {thresholds}")

    top_affected = undefined_features_df.sort_values("number_subjects_undefined", ascending=False).head(15)
    log(f"Top affected FC feature pairs (by subject count):\n" +
        top_affected[["feature_index", "roi_i_name", "roi_j_name", "number_subjects_undefined",
                      "percentage_subjects_undefined"]].to_string(index=False))
    log("NOTE: this is a data-quality/missingness pattern only -- these top pairs are dominated by "
        "combinations of the 19 constant-prone ROIs (Phase 4.1) and are NOT interpreted here as "
        "biomarkers or biologically meaningful connectivity findings.")

    # ── Fisher-Z readiness check (mathematical, not applied to real dataset) ──
    log(f"\nFISHER-Z READINESS: exact +1 correlations among defined entries = {exact_plus1}, "
        f"exact -1 correlations = {exact_minus1}, undefined correlations = {total_undefined}")
    clipping_required = (exact_plus1 > 0 or exact_minus1 > 0)
    log(f"Clipping before arctanh would be required: {clipping_required} "
        f"(arctanh(+/-1) = +/-infinity; NOT applied here -- Fisher-Z is not run on real data in this phase)")
    fisher_z_ready_df = pd.DataFrame([{
        "defined_entries_total": int(780 * 6670 - total_undefined),
        "undefined_entries_total": total_undefined,
        "exact_plus1_count": exact_plus1, "exact_minus1_count": exact_minus1,
        "clipping_required_before_arctanh": clipping_required,
        "fisher_z_applied_to_real_data": False,
        "fisher_z_status": "MATHEMATICALLY READY FOR DEFINED ENTRIES ONLY -- undefined entries "
                           "remain undefined under arctanh (NaN in, NaN out); NOT executed this phase",
    }])
    fisher_z_ready_df.to_csv(OUT_DIR / "fisher_z_readiness_summary.csv", index=False)
    log("fisher_z_readiness_summary.csv written.")

    # ── SVM-RFE NaN compatibility (empirically tested against installed sklearn) ──
    log("\nEmpirically testing installed scikit-learn's NaN tolerance (small synthetic arrays, not "
        "real FC data; no SVM-RFE is trained on this project's data anywhere in this script)...")
    import sklearn
    from sklearn.svm import SVC
    from sklearn.feature_selection import RFE
    from sklearn.preprocessing import StandardScaler

    X_test = np.array([[1.0, np.nan, 5.0], [2.0, 3.0, 1.0], [3.0, 1.0, 2.0], [4.0, 2.0, 3.0]])
    y_test = np.array([0, 1, 0, 1])
    scaler_ok = False
    try:
        StandardScaler().fit(X_test)
        scaler_ok = True
    except Exception:
        scaler_ok = False
    svc_ok = False
    svc_error = None
    try:
        SVC(kernel="linear").fit(X_test, y_test)
        svc_ok = True
    except Exception as exc:
        svc_error = f"{type(exc).__name__}: {exc}"
    rfe_ok = False
    rfe_error = None
    try:
        RFE(SVC(kernel="linear"), n_features_to_select=1).fit(X_test, y_test)
        rfe_ok = True
    except Exception as exc:
        rfe_error = f"{type(exc).__name__}: {exc}"

    log(f"  sklearn version: {sklearn.__version__}")
    log(f"  StandardScaler.fit() accepts NaN: {scaler_ok}")
    log(f"  SVC.fit() accepts NaN: {svc_ok}  (error if not: {svc_error})")
    log(f"  RFE(SVC).fit() accepts NaN: {rfe_ok}  (error if not: {rfe_error})")

    svm_rfe_md = f"""# SVM-RFE NaN Compatibility Investigation

**No SVM-RFE was trained on this project's FC data. This is an isolated compatibility check using
small synthetic arrays against the installed scikit-learn ({sklearn.__version__}).**

## Empirical results

| Component | Accepts NaN? |
|---|---|
| `sklearn.preprocessing.StandardScaler` | {'YES' if scaler_ok else 'NO'} |
| `sklearn.svm.SVC` (the classifier SVM-RFE wraps) | {'YES' if svc_ok else 'NO'} |
| `sklearn.feature_selection.RFE(SVC(...))` | {'YES' if rfe_ok else 'NO'} |

{'`SVC.fit()` raised: `' + svc_error + '`' if not svc_ok else ''}
{'`RFE(SVC).fit()` raised: `' + rfe_error + '`' if not rfe_ok else ''}

## What would mathematically happen

`SVC` (and therefore `RFE(SVC, ...)`, the standard scikit-learn SVM-RFE construction) validates its
input with scikit-learn's internal `check_array`, which by default requires all values to be finite.
Passing the 780×6,670 diagnostic FC matrix from this phase directly into `RFE(SVC(...))` would raise
`ValueError: Input X contains NaN` immediately, before any fitting occurs — it would not silently
produce a degraded or approximate result; it fails hard.

## Conclusion

**"An additional missing-value handling decision is required before SVM-RFE."**

This phase does not invent that decision. The options remain those enumerated in Phase 4.2's
`METHODOLOGICAL_DECISION.md` (retain-with-NaN requires a downstream imputation/removal step before
SVM-RFE specifically, even if NaN is preserved through Phase 5A and Fisher-Z; exclude-subjects;
exclude-ROIs; or a documented numeric convention — none of which is paper-specified).
"""
    with open(OUT_DIR / "svm_rfe_nan_compatibility.md", "w") as f:
        f.write(svm_rfe_md)
    log("svm_rfe_nan_compatibility.md written.")

    # ── structural option comparison (no model training) ─────────────────
    structural_rows = [
        {"option": "A: 780 subjects, 116 ROIs, NaN preserved", "subjects": 780, "rois": 116,
         "fc_features": 6670, "undefined_entries": total_undefined,
         "fully_numeric": False, "requires_further_decision_before_svm_rfe": True},
        {"option": "B: 733 subjects (47 excluded), 116 ROIs", "subjects": 733, "rois": 116,
         "fc_features": 6670, "undefined_entries": 0,
         "fully_numeric": True, "requires_further_decision_before_svm_rfe": False},
        {"option": "C: 780 subjects, 97 ROIs (19 excluded)", "subjects": 780, "rois": 97,
         "fc_features": 4656, "undefined_entries": 0,
         "fully_numeric": True, "requires_further_decision_before_svm_rfe": False},
    ]
    structural_df = pd.DataFrame(structural_rows)
    structural_df.to_csv(OUT_DIR / "structural_option_comparison.csv", index=False)
    log("structural_option_comparison.csv written (structural only -- no model accuracy compared, "
        "no training performed).")

    # ── audit ───────────────────────────────────────────────────────────
    post_guard = guard_fingerprints()
    guard_unchanged = (pre_guard == post_guard)
    status_ok = status_ok and guard_unchanged
    log(f"\nAUDIT: Phase 1-4.2 files unchanged: {'PASS' if guard_unchanged else 'FAIL'}")
    log("AUDIT: no full FC dataset written to disk anywhere -- per-subject 116x116 matrices existed "
        "only in-memory within the loop above and were immediately reduced to aggregate counts; "
        "confirmed by code review (no np.save/to_csv of any per-subject FC matrix).")
    log("AUDIT: Fisher-Z (arctanh) was NOT applied to the real 780-subject dataset anywhere in this "
        "script -- only counts of exact +/-1 values and a readiness determination were computed.")
    log("AUDIT: SVM-RFE/SSAE/classifier training NOT performed on real data -- the sklearn NaN check "
        "used a 4x3 synthetic array, not this project's FC data.")
    log("AUDIT: source .1D files opened read-only (np.loadtxt only) -- confirmed by code review.")

    phase5a_status = "PASS" if status_ok else "FAIL"
    fisher_z_status = "BLOCKED" if total_undefined > 0 else "READY"
    final_decision_status = "REQUIRED"

    summary = {
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "cohort": {"total": n_cohort, "asd": n_asd, "control": n_control},
        "rois": 116, "fc_features": 6670,
        "undefined_pearson_entries": total_undefined,
        "expected_undefined_entries": EXPECTED_UNDEFINED_TOTAL,
        "cross_check_pass": cross_check_pass,
        "feature_indexing_pass": True,
        "pearson_validation_pass": validation_pass,
        "fisher_z_readiness": fisher_z_status,
        "fisher_z_exact_plus1": exact_plus1, "fisher_z_exact_minus1": exact_minus1,
        "fisher_z_clipping_required": clipping_required,
        "svm_rfe_nan_compatible": svc_ok,
        "final_fc_preprocessing_decision": final_decision_status,
        "phase5a_status": phase5a_status,
        "phase5_status": "BLOCKED" if final_decision_status == "REQUIRED" else "READY",
        "audit": {"previous_phases_unchanged": guard_unchanged, "fc_dataset_written": False,
                  "fisher_z_on_real_data": False, "svm_rfe_trained": False, "ssae_trained": False,
                  "classifier_trained": False, "xai_run": False, "roar_run": False,
                  "downloads_performed": False},
    }
    with open(OUT_DIR / "phase5a_summary.json", "w") as f:
        json.dump(summary, f, indent=2, default=str)
    with open(OUT_DIR / "phase5a_summary.txt", "w") as f:
        f.write(json.dumps(summary, indent=2, default=str))
    log("phase5a_summary.json / .txt written.")

    audit_lines.append("Output files: fc_feature_index.csv, undefined_fc_features.csv, "
                        "undefined_fc_subject_summary.csv, undefined_fc_site_summary.csv, "
                        "fc_missingness_thresholds.csv, fisher_z_readiness_summary.csv, "
                        "svm_rfe_nan_compatibility.md, structural_option_comparison.csv, "
                        "phase5a_summary.json/.txt, PHASE5A_RESOLUTION.md")
    with open(OUT_DIR / "phase5a_audit.log", "w") as f:
        f.write("\n".join(audit_lines))
    print(f"\nAll Phase 5A outputs written to {OUT_DIR}")

    return summary, {
        "total_undefined": total_undefined, "cross_check_pass": cross_check_pass,
        "validation_pass": validation_pass, "exact_plus1": exact_plus1, "exact_minus1": exact_minus1,
        "clipping_required": clipping_required, "svc_ok": svc_ok, "guard_unchanged": guard_unchanged,
        "thresholds": thresholds, "top_affected": top_affected,
    }


if __name__ == "__main__":
    main()
